import assert from 'node:assert/strict';
import { QueryClient } from '@tanstack/query-core';
import { widgetDataFromCache, publishWidgets } from './publish';
import { buildNextDue, buildGrades, nextDueTimeline } from './build';
import { upcomingRange } from '../planner/range';
import { createDateContext } from '../../lib/dates';
import { summarizeDue } from '../../lib/due';
import { widgetWrites } from '../../i18n/checks/background.stubs.mjs';
const client = new QueryClient();
const now = new Date();
const range = upcomingRange(now);
const key = ['A', 'planner', 'items', range.start.toISOString(), range.end.toISOString()];
const pending = client.getQueryCache().build(client, { queryKey: key });
assert.equal(widgetDataFromCache(client, 'A').items, null, 'pending is unknown, not empty');
pending.setState({ status: 'error', error: new Error('offline') });
assert.equal(widgetDataFromCache(client, 'A').items, null, 'failed is unknown, not empty');
const item = { id: 'assignment:1', plannableType: 'assignment', plannableId: '1', kind: 'assignment', title: 'Next assignment', dueAt: new Date(+now + 86400000), courseId: 'c', status: 'open', markedComplete: false, dismissed: false };
client.setQueryData(['B', ...key.slice(1)], [item]);
assert.equal(widgetDataFromCache(client, 'A').items, null, 'account isolation');
client.setQueryData(['A', 'planner', 'items', now.toISOString(), new Date(+now + 1000).toISOString()], []);
assert.equal(widgetDataFromCache(client, 'A').items, null, 'short empty range cannot clear Home');
client.setQueryData(key, [item]);
assert.deepEqual(widgetDataFromCache(client, 'A').items, [item]);
const props = buildNextDue([item], [], now);
assert.equal(props.title, summarizeDue([item], now).next.title);
publishWidgets({ items: null, courses: null, announcements: null, grades: null }, now);
assert.equal(widgetWrites.findLast(w => w.name === 'next').props.state, 'waiting');
assert.match(widgetWrites.findLast(w => w.name === 'next').props.message, /Open Easel/);
publishWidgets(widgetDataFromCache(client, 'A'), now);
assert.equal(widgetWrites.findLast(w => w.name === 'next').props.title, item.title);
client.setQueryData(key, []);
assert.deepEqual(widgetDataFromCache(client, 'A').items, [], 'successful empty window remains empty');
const timeline = nextDueTimeline([item], [], now, createDateContext());
assert.equal(timeline[0].props.title, item.title);
assert.ok(timeline.every((entry, i) => !i || entry.date >= timeline[i - 1].date));
const hidden = buildGrades([{ id: 'c', code: 'COURSE', name: 'Course', hidden: true, restricted: false, score: 99, grade: 'A', color: '#123456' }], [], true);
assert.equal(hidden.rows[0].detail, 'Hidden');
assert.ok(!JSON.stringify(hidden).includes('99'));
client.clear();
console.log('PASS widget pending/error/partial/account isolation, Home parity, waiting/empty states, iOS timeline and hidden grades');
