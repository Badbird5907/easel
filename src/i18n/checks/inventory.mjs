/** Candidate inventory, not a count of confirmed untranslated messages. Run from project root. */
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
const rows = [];
const uiProps =
  /^(title|label|subtitle|description|placeholder|accessibilityLabel|accessibilityHint|header|footer|message|doneLabel|currentHint)$/;
function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (file.startsWith('src/i18n') || /\.(check|test)\./.test(file)) continue;
    if (entry.isDirectory()) {
      scan(file);
      continue;
    }
    if (!/\.tsx?$/.test(file)) continue;
    const source = fs.readFileSync(file, 'utf8');
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    function visit(node) {
      let text;
      if (ts.isJsxText(node)) text = node.text.trim();
      if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
        const parent = node.parent;
        const ui =
          (ts.isJsxAttribute(parent) || ts.isPropertyAssignment(parent)) &&
          uiProps.test(parent.name.getText(ast));
        if (ui || /^[A-Z][\s\S]*\s[a-zA-Z]/.test(node.text)) text = node.text;
        if (ts.isImportDeclaration(parent) || ts.isExportDeclaration(parent)) text = undefined;
      }
      if (ts.isTemplateExpression(node) && /[A-Za-z]{2}/.test(node.head.text)) text = node.getText(ast);
      if (node.parent && ts.isCallExpression(node.parent) && node.parent.expression.getText(ast) === 't')
        text = undefined;
      if (text && /[A-Za-z]/.test(text) && !text.includes('@/')) {
        const parts = file.split('/');
        const workstream =
          parts[1] === 'features'
            ? `features/${parts[2]}`
            : parts[1] === 'app'
              ? `routes/${parts.slice(2, -1).join('/') || 'root'}`
              : parts[1];
        rows.push({
          workstream,
          path: file,
          line: ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1,
          text,
        });
      }
      ts.forEachChild(node, visit);
    }
    visit(ast);
  }
}
scan('src');
const grouped = new Map();
for (const row of rows) {
  if (!grouped.has(row.workstream)) grouped.set(row.workstream, new Map());
  const files = grouped.get(row.workstream);
  files.set(row.path, (files.get(row.path) ?? 0) + 1);
}
let md =
  '# Remaining localization candidate inventory\n\nGenerated by `node src/i18n/checks/inventory.mjs`. Counts are AST candidates, not confirmed strings: UI literal props, JSX prose, prose literals and template expressions. Includes API-generated English messages and may include technical literals; excludes catalogs, imports and check files. Manually review before migrating. Never translate Canvas/user content.\n\n';
for (const [group, files] of [...grouped].sort()) {
  md += `## ${group} (${[...files.values()].reduce((a, b) => a + b, 0)} candidates)\n\n| Path | Count |\n| --- | ---: |\n`;
  for (const [file, count] of [...files].sort()) md += `| \`${file}\` | ${count} |\n`;
  md += '\n';
}
fs.writeFileSync('src/i18n/MIGRATION.md', md);
fs.writeFileSync('src/i18n/checks/inventory.json', JSON.stringify(rows, null, 2) + '\n');
console.log(
  `${rows.length} candidates in ${grouped.size} workstreams; see MIGRATION.md and checks/inventory.json`,
);
